/* Real renderRoom/renderBattleRoom DOM; deterministic geometry, no network. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const dom = new JSDOM('<div id="app"></div><div id="toast" hidden></div>', { url: 'http://localhost', runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.requestAnimationFrame = () => 0;
Object.defineProperty(w.HTMLElement.prototype, 'clientHeight', { configurable: true, get() { return this.id === 'journal-log' ? 200 : 0; } });
Object.defineProperty(w.HTMLElement.prototype, 'scrollHeight', { configurable: true, get() { return this.id === 'journal-log' ? this.querySelectorAll('[data-event-id]').length * 40 : 0; } });
w.HTMLElement.prototype.getBoundingClientRect = function () {
  const log = this.closest('#journal-log');
  const top = this.dataset.eventId && log ? [...log.querySelectorAll('[data-event-id]')].indexOf(this) * 40 - log.scrollTop : 0;
  return { top, bottom: top + (this.dataset.eventId ? 40 : 200), height: this.dataset.eventId ? 40 : 200, left: 0, right: 500, width: 500 };
};
w.eval(fs.readFileSync(path.join(root, 'frontend/live-log.js'), 'utf8'));
const event = id => ({ id, kind: 'roll', text: `事件 ${id}`, roll: { total: 15, selected: 12, modifier: 3, success: true } });
const all = Array.from({ length: 20 }, (_, i) => event(i + 11));
const mount = events => {
  w.HexBoundLiveLog.capture('unit');
  w.document.querySelector('#app').innerHTML = '<div id="journal-log" class="journal-log" role="log"></div>';
  return w.HexBoundLiveLog.mount({ key: 'unit', placeholder: w.document.querySelector('#journal-log'), events, renderEvent: e => `<article><p>${e.text}</p><details><summary>骰子</summary>15</details></article>` });
};
let log = mount(all);
assert.equal(log.scrollTop, 600, 'initial log follows bottom');
const first = log.querySelector('[data-event-id="11"]');
first.querySelector('details').open = true;
assert.equal(mount(all), log, 'snapshot preserves scroll surface identity');
assert.equal(log.querySelector('[data-event-id="11"]'), first, 'snapshot preserves event identity');
assert(first.querySelector('details').open, 'snapshot preserves expanded roll');
mount([...all, event(31)]);
assert.equal(log.scrollTop, 640, 'new events follow when at bottom');
log.scrollTop = 120;
log.dispatchEvent(new w.Event('scroll'));
mount([...all, event(31), event(32)]);
assert.equal(log.scrollTop, 120, 'reading older content does not jump');
let jump = w.document.querySelector('.log-new-events');
assert(!jump.hidden && jump.textContent.startsWith('1 '));
mount([...all, event(31), event(32)]);
assert(jump.textContent.startsWith('1 '), 'identical snapshots do not inflate unread');
mount([event(9), event(10), ...all, event(32)]);
assert.equal(log.scrollTop, 200, 'prepending history preserves visible event offset');
assert.equal(log.querySelectorAll('[data-event-id="11"]').length, 1, 'overlapping history is deduplicated');
jump.click();
assert.equal(log.scrollTop, log.scrollHeight - log.clientHeight);
assert(jump.hidden);

// Load the actual application without boot/network, expose only a test render seam.
w.HexBoundLiveLog.clear();
const source = fs.readFileSync(path.join(root, 'frontend/app.js'), 'utf8').replace(/^boot\(\);$/m, '');
w.eval(source + `\nwindow.renderFixture=(next)=>{room=next;session={room_id:next.id,member_id:'p',invite_code:'ABCDEF'};catalog={llm:{configured:false}};connected=true;renderRoom();};`);
const fixture = { id: 'fixture', name: '日志验收', status: 'playing', mode: 'preset', interaction_mode: 'freeform', version: 1, host_id: 'p', invite_code: 'ABCDEF', party: [{ id: 'p', name: '旅人', class_id: 'fighter', hp: 10, max_hp: 10, ac: 15, abilities: { str: 16, dex: 12 }, online: true }], scene: { title: '场景', text: '继续冒险', objective: '探索' }, events: all, available_actions: [], free_actions: { recipes: [] } };
w.renderFixture(fixture);
log = w.document.querySelector('#journal-log');
assert.equal(log.querySelectorAll('[data-event-id]').length, 20, 'exploration uses real live-log integration');
const storyRow = log.querySelector('[data-event-id="11"]');
w.renderFixture({ ...fixture, version: 2, events: [...all, event(31)] });
assert.equal(w.document.querySelector('#journal-log'), log);
assert.equal(log.querySelector('[data-event-id="11"]'), storyRow);
assert.equal(log.scrollTop, 640);
const combat = { active: true, round: 1, turn_actor_id: 'p', order: ['p', 'enemy'], enemies: [{ id: 'enemy', name: '对手', hp: 20, max_hp: 20, ac: 12 }], action_used: false };
w.renderFixture({ ...fixture, combat });
const battleLog = w.document.querySelector('#journal-log');
assert(battleLog.querySelector('[data-event-id="11"]'), 'battle uses keyed events');
const battleRow = battleLog.querySelector('[data-event-id="11"]');
battleLog.scrollTop = 120;
battleLog.dispatchEvent(new w.Event('scroll'));
w.renderFixture({ ...fixture, combat, events: [...all, event(31)] });
assert.equal(w.document.querySelector('#journal-log'), battleLog);
assert.equal(battleLog.querySelector('[data-event-id="11"]'), battleRow);
assert.equal(battleLog.scrollTop, 120);
assert(!battleLog.nextElementSibling.hidden, 'battle offers jump to new events');
console.log('PASS stable node/event identity, bottom follow, read anchor, unread jump, history dedupe, exploration+battle render integration');
dom.window.close();
